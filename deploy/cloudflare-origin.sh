#!/usr/bin/env bash
# ITPidia: lock the VPS origin behind Cloudflare. Run on the VPS as root: sudo bash cloudflare-origin.sh
#  1. nginx reads the real visitor IP from CF-Connecting-IP (only when the request really comes from Cloudflare),
#     so rate limiting and logs work per visitor instead of per Cloudflare edge.
#  2. ufw allows ports 80/443 only from Cloudflare, so nobody can bypass the proxy by hitting the VPS IP directly.
# Re-run it every few months (Cloudflare occasionally adds ranges).
set -euo pipefail

v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)
[ -n "$v4" ] && [ -n "$v6" ] || { echo "Could not download Cloudflare IP list" >&2; exit 1; }

conf=/etc/nginx/conf.d/cloudflare-realip.conf
{
  echo "# Generated by cloudflare-origin.sh on $(date -u +%F)"
  for ip in $v4 $v6; do echo "set_real_ip_from $ip;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > "$conf"
nginx -t
systemctl reload nginx

ufw allow OpenSSH
# Remove any open-to-everyone web rules, then allow web traffic from Cloudflare only.
for rule in 80 443 80/tcp 443/tcp "Nginx Full" "Nginx HTTP" "Nginx HTTPS" "80,443/tcp"; do
  ufw --force delete allow "$rule" >/dev/null 2>&1 || true
done
for ip in $v4 $v6; do
  ufw allow proto tcp from "$ip" to any port 80,443 comment 'cloudflare' >/dev/null
done
ufw default deny incoming
ufw --force enable
ufw status | head -20
echo "Done. Web ports now accept Cloudflare only."
